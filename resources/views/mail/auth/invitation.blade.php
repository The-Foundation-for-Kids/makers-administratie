# Welkom als maakster bij The Foundation for Kids!

Wat fijn dat je jouw creativiteit wilt inzetten om een kind blij te maken met iets wat speciaal voor hem of haar gemaakt is. Vanaf nu maak jij deel uit van een groep enthousiaste vrijwilligers die samen iets bijzonders willen betekenen.

Hierbij ontvang je de uitnodiging voor ons online aanvragensysteem, met de button kun je jouw account activeren en een zelfgekozen wachtwoord instellen.

<x-mail::button :url='$acceptUrl'>
Account activeren
</x-mail::button>

Zodra je account is geactiveerd, kun je inloggen in het aanvragensysteem en zelf een aanvraag uitzoeken. Je krijgt hierbij informatie over het kind en de wensen, zodat je een persoonlijk en passend kledingsetje kunt maken.

Je hebt hiervoor 4 weken de tijd, of 6 weken wanneer het om een verjaardagsetje gaat. Zodra je setje klaar is, gaat het via een inzamelpunt naar de instantie die de aanvraag heeft gedaan.

In het aanvragensysteem staat onder ‘Handleiding maakster’ stap voor stap uitgelegd hoe alles werkt.

En natuurlijk hoef je het niet allemaal alleen uit te zoeken. Heb je vragen of loop je ergens tegenaan? Neem gerust contact op met Monique Latta via Messenger of stuur een mail naar info@thefoundationforkids.nl. We helpen je graag!

